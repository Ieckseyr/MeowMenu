# gen_texture_path_embed.ps1 - Convert texture_path.json to a C++ header
#
# Embeds the texture path mapping JSON as chunked raw string literals in a C++ header.
# This is an optional manual refresh step: re-run it only when the icon library changes.
# Neither the build nor the runtime depends on this script or on texture_path.json --
# src/embedded_texture_path.h ships with the source, so a missing external JSON
# does not affect building or loading the plugin.
#
# Usage:
#   powershell -File gen_texture_path_embed.ps1 -OutPath "src/embedded_texture_path.h" -JsonFile "../Meow/textures/texture_path.json"
param(
    [Parameter(Mandatory=$true)][string]$OutPath,
    [Parameter(Mandatory=$true)][string]$JsonFile
)

if (-not (Test-Path $JsonFile)) {
    Write-Error "[gen_texture_path_embed] JSON file not found: $JsonFile"
    exit 1
}

# Read as UTF-8 without BOM
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$content = [System.IO.File]::ReadAllText($JsonFile, $utf8NoBom)

# Normalize CRLF to LF: MSVC folds CRLF to LF inside raw string literals anyway,
# so emitting LF keeps the header stable across checkouts and line-ending settings.
$content = $content -replace "`r`n", "`n"

# Note: Do not validate with ConvertFrom-Json - PowerShell's JSON parser is
# case-insensitive and reports false duplicate-key errors for keys that
# differ only in case (e.g. windCharged vs windcharged). The C++ side uses
# nlohmann::json which is case-sensitive and handles this correctly.

# MSVC rejects string literals longer than ~16380 bytes (error C2026), so the
# JSON is stored as chunks and reassembled by the C++ side before parsing.
# The raw-string delimiter must stay within 16 characters for MSVC (error C3512).
$chunkSize = 12000
$delim = "MEOWTEXEMBEDV1"

$terminator = ')' + $delim + '"'
if ($content.Contains($terminator)) {
    Write-Error "[gen_texture_path_embed] content contains the raw-string terminator $terminator"
    exit 1
}

$sb = New-Object System.Text.StringBuilder

[void]$sb.AppendLine("// AUTO-GENERATED BY gen_texture_path_embed.ps1 - DO NOT EDIT")
[void]$sb.AppendLine("// Source: $JsonFile")
[void]$sb.AppendLine("// Embedded icon library (texture_path.json content) used by IconValidator.")
[void]$sb.AppendLine("// Chunked because MSVC limits a single string literal to ~16380 bytes (C2026).")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#include <cstddef>")
[void]$sb.AppendLine("#include <string>")
[void]$sb.AppendLine("#include <string_view>")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("namespace meowmenu {")
[void]$sb.AppendLine("namespace embedded_texture_path {")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("inline constexpr std::string_view chunks[] = {")

$offset = 0
$count = 0
while ($offset -lt $content.Length) {
    $len = [Math]::Min($chunkSize, $content.Length - $offset)
    # Raw string literal syntax: R"DELIM(content)DELIM"
    [void]$sb.Append('R"')
    [void]$sb.Append($delim)
    [void]$sb.Append('(')
    [void]$sb.Append($content.Substring($offset, $len))
    [void]$sb.Append(')')
    [void]$sb.Append($delim)
    [void]$sb.AppendLine('",')
    $offset += $len
    $count++
}

[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("inline constexpr size_t chunkCount = sizeof(chunks) / sizeof(chunks[0]);")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("// Reassemble the complete JSON text from all chunks")
[void]$sb.AppendLine("inline std::string text() {")
[void]$sb.AppendLine("    std::string out;")
[void]$sb.AppendLine("    size_t total = 0;")
[void]$sb.AppendLine("    for (auto const& chunk : chunks) total += chunk.size();")
[void]$sb.AppendLine("    out.reserve(total);")
[void]$sb.AppendLine("    for (auto const& chunk : chunks) out.append(chunk);")
[void]$sb.AppendLine("    return out;")
[void]$sb.AppendLine("}")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("} // namespace embedded_texture_path")
[void]$sb.AppendLine("} // namespace meowmenu")
[void]$sb.AppendLine("")

[System.IO.File]::WriteAllText($OutPath, $sb.ToString(), $utf8NoBom)
Write-Host "[gen_texture_path_embed] Wrote $OutPath ($($content.Length) chars in $count chunks from $JsonFile)"
