# gen_texture_path_embed.ps1 - Convert texture_path.json to a C++ header
#
# Embeds the texture path mapping JSON as a raw string literal in a C++ header.
# Called by xmake before_build to generate src/embedded_texture_path.h.
#
# Usage:
#   powershell -File gen_texture_path_embed.ps1 -OutPath "src/embedded_texture_path.h" -JsonFile "../Meow/textures/texture_path.json"
param(
    [Parameter(Mandatory=$true)][string]$OutPath,
    [Parameter(Mandatory=$true)][string]$JsonFile
)

if (-not (Test-Path $JsonFile)) {
    Write-Error "[gen_texture_path_embed] JSON file not found: $JsonFile"
    exit 1
}

# Read as UTF-8 without BOM
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$content = [System.IO.File]::ReadAllText($JsonFile, $utf8NoBom)

# Note: Do not validate with ConvertFrom-Json - PowerShell's JSON parser is
# case-insensitive and reports false duplicate-key errors for keys that
# differ only in case (e.g. windCharged vs windcharged). The C++ side uses
# nlohmann::json which is case-sensitive and handles this correctly.

# Use a unique delimiter to avoid conflicts with JSON content
$delim = "MEOW_TEX_PATH_JSON_EMBED_V1"

$sb = New-Object System.Text.StringBuilder

[void]$sb.AppendLine("// AUTO-GENERATED BY gen_texture_path_embed.ps1 - DO NOT EDIT")
[void]$sb.AppendLine("// Source: $JsonFile")
[void]$sb.AppendLine("// Embedded texture_path.json data for icon validation/repair")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#include <cstddef>")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("namespace meowmenu {")
[void]$sb.AppendLine("namespace embedded_texture_path {")
[void]$sb.AppendLine("")
# Raw string literal syntax: R"DELIM(content)DELIM"
[void]$sb.Append('constexpr const char data[] = R"')
[void]$sb.Append($delim)
[void]$sb.Append('(')
[void]$sb.Append($content)
[void]$sb.Append(')')
[void]$sb.Append($delim)
[void]$sb.AppendLine('";')
[void]$sb.AppendLine("")
[void]$sb.AppendLine("constexpr size_t size = sizeof(data) - 1; // excluding trailing null")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("} // namespace embedded_texture_path")
[void]$sb.AppendLine("} // namespace meowmenu")
[void]$sb.AppendLine("")

[System.IO.File]::WriteAllText($OutPath, $sb.ToString(), $utf8NoBom)
Write-Host "[gen_texture_path_embed] Wrote $OutPath ($($content.Length) chars from $JsonFile)"
